import json
from pathlib import Path


# Positions that count as pitcher slots
PITCHER_POSITIONS = {"SP", "RP", "P"}


class LeagueConfig:
    """Loads and validates league configuration."""

    def __init__(self, config_path: str | Path = "config/league_config.json"):
        self.path = Path(config_path)
        self._data = self._load()
        self._validate()

    def _load(self) -> dict:
        with open(self.path, "r", encoding="utf-8") as f:
            return json.load(f)

    def _validate(self) -> None:
        required_keys = ["team_count", "roster_slots", "scoring_format", "scoring_categories", "draft_type"]
        missing = [k for k in required_keys if k not in self._data]
        if missing:
            raise ValueError(f"Missing required config keys: {missing}")

        if self._data["team_count"] < 2:
            raise ValueError("team_count must be at least 2")

    @property
    def team_count(self) -> int:
        return self._data["team_count"]

    @property
    def roster_slots(self) -> dict[str, int]:
        return self._data["roster_slots"]

    @property
    def scoring_format(self) -> str:
        return self._data["scoring_format"]

    @property
    def scoring_categories(self) -> dict[str, list[str]]:
        return self._data["scoring_categories"]

    @property
    def draft_type(self) -> str:
        return self._data["draft_type"]

    @property
    def draft_position(self) -> int | None:
        return self._data.get("draft_position")

    @draft_position.setter
    def draft_position(self, value: int) -> None:
        self._data["draft_position"] = value

    @property
    def my_team_name(self) -> str:
        return self._data.get("my_team_name", "My Team")

    @property
    def total_roster_size(self) -> int:
        return sum(self.roster_slots.values())

    @property
    def total_draft_rounds(self) -> int:
        return self.total_roster_size

    @property
    def min_innings_per_week(self) -> int | None:
        return self._data.get("min_innings_per_week")

    def pick_order(self, round_number: int) -> int:
        """Calculate my pick position in a given round (snake draft aware)."""
        if self.draft_position is None:
            raise ValueError("Draft position not set")

        if self.draft_type in ("snake", "live-standard"):
            if round_number % 2 == 1:
                pick_in_round = self.draft_position
            else:
                pick_in_round = self.team_count - self.draft_position + 1
        else:
            pick_in_round = self.draft_position

        return (round_number - 1) * self.team_count + pick_in_round

    def picks_until_mine(self, current_pick: int, round_number: int) -> int:
        """How many picks until my next pick."""
        my_pick = self.pick_order(round_number)
        if current_pick >= my_pick:
            my_pick = self.pick_order(round_number + 1)
        return my_pick - current_pick


class DerivedConfig:
    """Loads derived configuration generated by setup.py.

    Contains all computed constants that depend on league settings:
    season targets, stat classifications, flex eligibility, tier boundaries,
    category tag thresholds, tracked positions, etc.
    """

    def __init__(self, config_path: str | Path = "config/derived_config.json"):
        self.path = Path(config_path)
        self._data = self._load()

    def _load(self) -> dict:
        with open(self.path, "r", encoding="utf-8") as f:
            return json.load(f)

    @property
    def season_targets(self) -> dict[str, float]:
        return self._data["season_targets"]

    @property
    def counting_stats(self) -> set[str]:
        return set(self._data["counting_stats"])

    @property
    def ratio_stats(self) -> set[str]:
        return set(self._data["ratio_stats"])

    @property
    def inverted_stats(self) -> set[str]:
        return set(self._data["inverted_stats"])

    @property
    def hitting_cats(self) -> set[str]:
        return set(self._data["hitting_cats"])

    @property
    def pitching_cats(self) -> set[str]:
        return set(self._data["pitching_cats"])

    @property
    def tracked_positions(self) -> list[str]:
        return self._data["tracked_positions"]

    @property
    def tag_to_category(self) -> dict[str, str]:
        return self._data["tag_to_category"]

    @property
    def above_avg_thresholds(self) -> dict[str, float]:
        return self._data["above_avg_thresholds"]

    @property
    def flex_eligibility(self) -> dict[str, list[str]]:
        return self._data["flex_eligibility"]

    @property
    def flex_eligibility_sets(self) -> dict[str, set[str]]:
        return {k: set(v) for k, v in self._data["flex_eligibility"].items()}

    @property
    def tier_boundaries(self) -> list[int]:
        return self._data["tier_boundaries"]

    @property
    def category_tag_thresholds(self) -> dict[str, float]:
        return self._data["category_tag_thresholds"]

    @property
    def target_counts(self) -> dict[str, int]:
        return self._data.get("target_counts", {})

    @property
    def scarcity_deadlines(self) -> dict[str, int]:
        return self._data.get("scarcity_deadlines", {})
